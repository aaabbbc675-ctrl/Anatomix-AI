// فایل ۸ موتور تغذیه — زیرکامیت ۶-ج (بخش ۲.۷ سند: مکمل‌ها). محاسبه‌گر خالص
// روی weight_kg؛ هیچ مقداری اینجا هرگز چیزی را قفل/مسدود نمی‌کند (اصل ۱.۴) —
// فقط پیشنهاد عددی یا یادداشت متنی است، تصمیم مصرف همیشه با مربی/شاگرد می‌ماند.
//
// طبق قرارداد MEV تاییدشده (batch ۳): برای هر بازه‌ی مستند سند، پایین‌ترین
// نقطه به‌عنوان پیش‌فرض سیستم انتخاب می‌شود — همان الگوی کف چربی/کربو در
// فایل ۲ و پروتئین قبل‌خواب در فایل ۵.

import { PRE_SLEEP_PROTEIN_G } from "./file5_mealTiming.js";

// بازه‌ی سند: ۳-۵ گرم روزانه (مقدار نگه‌دارنده). برخلاف کافئین/هیدراتاسیون،
// این عدد مطلق است (نه g/kg) — سند خودش این‌طور نوشته.
const CREATINE_MIN_G = 3;

// بازه‌ی سند: ۳-۶ میلی‌گرم/کیلو، ۳۰-۶۰ دقیقه قبل تمرین. سند صراحتاً می‌گوید
// «اختیاری، فقط با تایید مربی» — برخلاف کراتین که چنین قیدی ندارد. این قید
// یک فیلد ورودی جدید در ایستگاه اول نمی‌خواهد (هیچ فرمولی به آن وابسته
// نیست)؛ فقط یک پرچم `caffeine_requires_coach_approval` در خروجی گذاشته
// می‌شود تا لایه‌ی UI تصمیم نمایش/فعال‌سازی را بگیرد.
const CAFFEINE_MIN_MG_PER_KG = 3;

// بازه‌ی سند: ۳۰-۴۰ میلی‌لیتر به ازای هر کیلوگرم وزن بدن (پایه، بدون جبران
// تعریق). سند برای جبران تعریق هیچ ضریب/فرمولی نمی‌دهد — فقط توصیف کیفی
// («+ جبران تعریق تمرین») — پس اینجا هم فقط یادداشت متنی است، نه فرمول ساختگی.
const HYDRATION_MIN_ML_PER_KG = 30;

function computeSupplementRecommendations({ weight_kg }) {
  return {
    creatine_g: CREATINE_MIN_G,

    // طبق بخش ۲.۷ سند، بازه‌ی پروتئین وی («۲۰-۴۰ گرم یا ۰.۲۵-۰.۴۰ گرم/کیلو»)
    // دقیقاً همان MEAL_PROTEIN_MIN_G_PER_KG/MEAL_PROTEIN_MAX_G_PER_KG فایل ۵
    // است — یعنی وی صرفاً یکی از راه‌های تامین پروتئین همان وعده است، نه یک
    // مکمل با قاعده‌ی مستقل. طبق اصل «یک منبع حقیقت» (هم‌الگوی کازئین)، اینجا
    // عدد جدیدی ساخته نمی‌شود، فقط ارجاع متنی به فایل ۵.
    whey_protein_note:
      "پروتئین وی صرفاً یکی از منابع تامین پروتئین همان وعده است؛ از بازه‌ی " +
      "پروتئین هر وعده در فایل ۵ استفاده کنید (MEAL_PROTEIN_MIN_G_PER_KG تا " +
      "MEAL_PROTEIN_MAX_G_PER_KG)، عدد جداگانه‌ای برای آن تعریف نشده.",

    // ارجاع مستقیم به فایل ۵ (نه عدد جدید) — چون سند بخش ۲.۷ و بخش ۲.۳ هر دو
    // دقیقاً همان «۳۰-۴۰ گرم پروتئین قبل‌خواب» را توصیف می‌کنند.
    casein_pre_sleep_g: PRE_SLEEP_PROTEIN_G,

    caffeine_mg: CAFFEINE_MIN_MG_PER_KG * weight_kg,
    caffeine_requires_coach_approval: true,

    // فقط یادداشت — طبق تصمیم تاییدشده، هیچ مقدار محاسبه‌شده‌ای ندارد.
    multivitamin_note:
      "۱ عدد با صبحانه. طبق موضع ACSM: در صورت دریافت کالری کافی از غذای " +
      "متنوع، معمولاً ضروری نیست.",

    hydration_base_ml: HYDRATION_MIN_ML_PER_KG * weight_kg,

    // فقط یادداشت متنی — سند هیچ ضریب/فرمولی برای جبران تعریق نداده، پس
    // اختراع یک فرمول اینجا همان خطایی است که این پروژه از ابتدا از آن
    // پرهیز کرده (اصل «بدون عدد حدسی»).
    hydration_sweat_compensation_note:
      "به مقدار پایه، بسته به شدت/مدت تمرین و آب‌وهوا، مقدار مناسبی برای " +
      "جبران تعریق اضافه کنید — سند فرمول ثابتی برای این بخش نداده است.",
  };
}

export {
  computeSupplementRecommendations,
  CREATINE_MIN_G,
  CAFFEINE_MIN_MG_PER_KG,
  HYDRATION_MIN_ML_PER_KG,
};
